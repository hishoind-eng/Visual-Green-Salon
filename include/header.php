    <script>
        document.addEventListener("DOMContentLoaded", function () {
            AOS.init();

            /*======================================
                SideBar Area JS
            =======================================*/

            var sidenavbar = document.getElementById("sideNavbar");
            var sidenavbarOverlay = document.getElementById("sideNavbarOverlay");
            var toggleBtn = document.getElementById("navbarMenuToggle");
            var closeBtn = document.getElementById("closeSideNavbar");

            if (!sidenavbar || !sidenavbarOverlay || !toggleBtn || !closeBtn) {
                return;
            }

            function shownavbar() {
                sidenavbar.classList.add("active");
                sidenavbarOverlay.classList.add("active");
                document.body.classList.add("no-scroll");
                toggleBtn.setAttribute("aria-expanded", "true");
            }

            function closenavbar() {
                sidenavbar.classList.remove("active");
                sidenavbarOverlay.classList.remove("active");
                document.body.classList.remove("no-scroll");
                toggleBtn.setAttribute("aria-expanded", "false");
            }

            // Toggle button (hamburger) - open sidebar
            toggleBtn.addEventListener("click", shownavbar);
            toggleBtn.addEventListener("keydown", function (e) {
                if (e.key === "Enter" || e.key === " ") {
                    e.preventDefault();
                    shownavbar();
                }
            });

            // Close (x) button
            closeBtn.addEventListener("click", closenavbar);
            closeBtn.addEventListener("keydown", function (e) {
                if (e.key === "Enter" || e.key === " ") {
                    e.preventDefault();
                    closenavbar();
                }
            });

            // Clicking the overlay/backdrop closes the sidebar
            sidenavbarOverlay.addEventListener("click", closenavbar);

            // Close when a nav link inside the sidebar is tapped (mobile UX)
            sidenavbar.querySelectorAll(".side-navbar-link a").forEach(function (link) {
                link.addEventListener("click", closenavbar);
            });

            // Close on Escape key for accessibility
            document.addEventListener("keydown", function (e) {
                if (e.key === "Escape") {
                    closenavbar();
                }
            });

            // Keep the sidebar/overlay state correct if the viewport is resized
            // past the breakpoint where the toggle button is hidden
            window.addEventListener("resize", function () {
                if (window.innerWidth > 1158) {
                    closenavbar();
                }
            });
        });
    </script>

